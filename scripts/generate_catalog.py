"""Generate the names of the connected appliances from the catalog of SEB.

    python scripts/generate_catalog.py <directory> [--fetch <domain.json>]

The directory holds the catalog of each market, as the SEB cloud answers it
to its app, in files named like `PRO_COO_GS_FR.json`. With `--fetch`, they are
downloaded there first: that needs the `assets/domain.json` file of the
Moulinex app, which holds the key of each kind of appliance. No account is
needed.

The result is written to `src/aiomoulinex/catalog.py`. Only the appliances
that connect to the cloud are kept: the others never show up in an account.
A brand does not write the name of an appliance the same in all its markets:
the name most of them use is kept, so that an appliance has one name per brand.
"""

from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import time
from urllib.error import URLError
from urllib.parse import urlencode
from urllib.request import Request, urlopen

from aiomoulinex import PROGRAMS, Region
from aiomoulinex.const import SEB_API_BASE, USER_AGENT

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "aiomoulinex" / "catalog.py"
HEADER = '''"""Names of the connected appliances of each brand.

Generated by ``scripts/generate_catalog.py`` from the catalog of SEB, do not
edit. The names are those of the Moulinex app: a brand has its own name for
an appliance.
"""

# Name by identifier in the catalog, then by brand.
MODELS: dict[str, dict[str, str]] = {
'''


def fetch(directory: Path, domain_file: Path) -> None:
    """Download the catalog of each market and kind of appliance."""
    keys = {
        domain["name"]: domain["apiKeys"][0]["value"]
        for domain in json.loads(domain_file.read_text())["domains"]
    }
    directory.mkdir(parents=True, exist_ok=True)
    for domain in PROGRAMS:
        for region in Region:
            query = urlencode(
                {"lang": region.language[:2], "market": f"GS_{region.market}"}
            )
            request = Request(  # noqa: S310
                f"{SEB_API_BASE}/common-api/v2/sync/appliances/0/?{query}",
                headers={"ApiKey": keys[domain], "User-Agent": USER_AGENT},
            )
            try:
                with urlopen(request, timeout=30) as response:  # noqa: S310
                    body = response.read()
            except URLError as err:
                # Not every kind of appliance is sold in every market.
                print(f"{domain} {region.market}: {err}")
                continue
            (directory / f"{domain}_GS_{region.market}.json").write_bytes(body)
            print(f"{domain} {region.market}: {len(body)} bytes")
            time.sleep(0.3)


def generate(directory: Path) -> str:
    """Return the module that holds the names found in the catalogs."""
    brands = {region.market: region.brand for region in Region}
    names: dict[str, dict[str, Counter[str]]] = {}
    for region in Region:
        for path in sorted(directory.glob(f"PRO_*_GS_{region.market}.json")):
            for appliance in json.loads(path.read_text()).get("objects", []):
                if appliance.get("thingType") and appliance.get("name"):
                    by_brand = names.setdefault(appliance["id"], {})
                    counter = by_brand.setdefault(brands[region.market], Counter())
                    counter[appliance["name"]] += 1
    lines = [HEADER]
    for identifier, by_brand in sorted(names.items()):
        lines.append(f"    {json.dumps(identifier)}: {{\n")
        lines.extend(
            # The most used name of the brand, the first one seen among equals.
            f"        {json.dumps(brand)}: "
            f"{json.dumps(counter.most_common(1)[0][0], ensure_ascii=False)},\n"
            for brand, counter in by_brand.items()
        )
        lines.append("    },\n")
    lines.append("}\n")
    return "".join(lines)


def main() -> None:
    """Run the command given on the command line."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("directory", type=Path)
    parser.add_argument("--fetch", type=Path, metavar="domain.json")
    arguments = parser.parse_args()
    if arguments.fetch is not None:
        fetch(arguments.directory, arguments.fetch)
    OUTPUT.write_text(generate(arguments.directory))
    print(f"Written to {OUTPUT}")


if __name__ == "__main__":
    main()
