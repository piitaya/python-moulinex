"""Generate what the library knows of the catalog and of the markets of SEB.

    python scripts/generate_catalog.py <directory> [--fetch <domain.json>]

The directory holds what the SEB cloud answers to its apps: the catalog of
each market in files named like `PRO_COO_GS_FR.json`, and the markets of each
app in files named like `CONFIG_PRO_MOU.json`. With `--fetch`, they are
downloaded there first: that needs the `assets/domain.json` file of the
Moulinex app, which holds the key of each app. No account is needed.

The result is written to `src/aiomoulinex/catalog.py`:

- The names of the appliances that connect to the cloud: the others never
  show up in an account. A brand does not write the name of an appliance the
  same in all its markets: the name most of them use is kept, so that an
  appliance has one name per brand.
- The regions of each country. Several regions serve Switzerland, one per
  language: the region that bears the name of the country comes first.
"""

from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import sys
import time
from urllib.error import URLError
from urllib.parse import urlencode
from urllib.request import Request, urlopen

from aiomoulinex import PROGRAMS, Region
from aiomoulinex.const import SEB_API_BASE, USER_AGENT

# The version of the Moulinex app the markets are asked for.
APP_VERSION = "35.1.0"
# The apps whose markets tell the region of a country: those of the brands, and
# the older ones of the Cookeo and of the Companion.
MARKET_DOMAINS = ("PRO_MOU", "PRO_TEF", "PRO_KRU", "PRO_TFA", *PROGRAMS)
OUTPUT = Path(__file__).resolve().parent.parent / "src" / "aiomoulinex" / "catalog.py"
HEADER = '''\
"""Names of the connected appliances of each brand, and regions of each country.

Generated by ``scripts/generate_catalog.py`` from what the SEB cloud answers
to the Moulinex app, do not edit. A brand has its own name for an appliance.
"""

# Name by identifier in the catalog, then by brand.
MODELS: dict[str, dict[str, str]] = {
'''


def download(path: str, key: str, target: Path) -> None:
    """Save what the SEB cloud answers to a request of its app."""
    request = Request(  # noqa: S310
        f"{SEB_API_BASE}{path}", headers={"ApiKey": key, "User-Agent": USER_AGENT}
    )
    try:
        with urlopen(request, timeout=30) as response:  # noqa: S310
            body = response.read()
    except URLError as err:
        # Not every kind of appliance is sold in every market.
        print(f"{target.name}: {err}")
        return
    target.write_bytes(body)
    print(f"{target.name}: {len(body)} bytes")
    time.sleep(0.3)


def fetch(directory: Path, domain_file: Path) -> None:
    """Download the markets of the apps, and the catalog of each market."""
    keys = {
        domain["name"]: domain["apiKeys"][0]["value"]
        for domain in json.loads(domain_file.read_text())["domains"]
    }
    directory.mkdir(parents=True, exist_ok=True)
    for domain in MARKET_DOMAINS:
        download(
            f"/common-api/v3/configurations/{keys[domain]}?version={APP_VERSION}",
            keys[domain],
            directory / f"CONFIG_{domain}.json",
        )
    for domain in PROGRAMS:
        for region in Region:
            query = urlencode(
                {"lang": region.language[:2], "market": f"GS_{region.market}"}
            )
            download(
                f"/common-api/v2/sync/appliances/0/?{query}",
                keys[domain],
                directory / f"{domain}_GS_{region.market}.json",
            )


def models(directory: Path) -> dict[str, dict[str, str]]:
    """Return the name of each connected appliance, by brand."""
    brands = {region.market: region.brand for region in Region}
    names: dict[str, dict[str, Counter[str]]] = {}
    for region in Region:
        for path in sorted(directory.glob(f"PRO_*_GS_{region.market}.json")):
            for appliance in json.loads(path.read_text()).get("objects", []):
                if appliance.get("thingType") and appliance.get("name"):
                    by_brand = names.setdefault(appliance["id"], {})
                    counter = by_brand.setdefault(brands[region.market], Counter())
                    counter[appliance["name"]] += 1
    # The most used name of the brand, the first one seen among equals.
    return {
        identifier: {
            brand: counter.most_common(1)[0][0] for brand, counter in by_brand.items()
        }
        for identifier, by_brand in sorted(names.items())
    }


def countries(directory: Path) -> dict[str, list[str]]:
    """Return the regions of each country the markets of the library serve."""
    regions = {region.profile_perimeter: region for region in Region}
    served: dict[str, set[Region]] = {}
    for domain in MARKET_DOMAINS:
        path = directory / f"CONFIG_{domain}.json"
        if not path.exists():
            sys.exit(f"{path.name} is missing, download it with --fetch")
        for market in json.loads(path.read_text()).get("markets", []):
            if (region := regions.get(market.get("profilePerimeter"))) is not None:
                for locale in market.get("locales", []):
                    if country := locale.get("country"):
                        served.setdefault(country.upper(), set()).add(region)
    if missing := set(Region) - set().union(*served.values()):
        sys.exit(f"No country found for {sorted(missing)}")
    return {
        country: [
            region.value
            for region in Region
            if region in candidates and region.market == country
        ]
        + [
            region.value
            for region in Region
            if region in candidates and region.market != country
        ]
        for country, candidates in sorted(served.items())
    }


def generate(directory: Path) -> str:
    """Return the module that holds what is found in the directory."""
    lines = [HEADER]
    for identifier, by_brand in models(directory).items():
        lines.append(f"    {json.dumps(identifier)}: {{\n")
        lines.extend(
            f"        {json.dumps(brand)}: {json.dumps(name, ensure_ascii=False)},\n"
            for brand, name in by_brand.items()
        )
        lines.append("    },\n")
    lines.append(
        "}\n\n# Regions by country, as the code of two letters of the country.\n"
    )
    lines.append("COUNTRIES: dict[str, tuple[str, ...]] = {\n")
    for country, regions in countries(directory).items():
        values = ", ".join(json.dumps(region) for region in regions)
        comma = "," if len(regions) == 1 else ""
        lines.append(f"    {json.dumps(country)}: ({values}{comma}),\n")
    lines.append("}\n")
    return "".join(lines)


def main() -> None:
    """Run the command given on the command line."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("directory", type=Path)
    parser.add_argument("--fetch", type=Path, metavar="domain.json")
    arguments = parser.parse_args()
    if arguments.fetch is not None:
        fetch(arguments.directory, arguments.fetch)
    OUTPUT.write_text(generate(arguments.directory))
    print(f"Written to {OUTPUT}")


if __name__ == "__main__":
    main()
